#!/usr/bin/env node
/**
 * Embed the running version and its CHANGELOG section into the client bundle.
 *
 * The in-app "what's new" dialog cannot read the repository or the npm page at
 * runtime, and fetching either would make an offline first run lie about the
 * version it ships. Generating the module at build time keeps the dialog tied
 * to the artifact actually installed: a new release's bundle carries its own
 * notes.
 *
 * Runs before `tsc`/`tsdown` in the package's `bundle` script; the generated
 * file is committed so a checkout can type-check before its first build.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { changelogSection } from './changelog-section.mjs'

const root = new URL('../', import.meta.url)
const packageJson = JSON.parse(readFileSync(new URL('packages/dsh-models-router/package.json', root), 'utf8'))
const changelog = readFileSync(new URL('CHANGELOG.md', root), 'utf8')
const section = changelogSection(packageJson.version, changelog)
if (section === undefined || section === '') {
  console.error(`CHANGELOG.md has no non-empty section for ${packageJson.version}`)
  process.exit(1)
}

const source = `/** Generated by scripts/embed-changelog.mjs from CHANGELOG.md — do not edit. */
export const RELEASE_VERSION = ${JSON.stringify(packageJson.version)}
export const RELEASE_NOTES = ${JSON.stringify(section)}
`
const target = fileURLToPath(new URL('packages/dsh-models-router/src/release.generated.ts', root))
writeFileSync(target, source)
console.log(`embedded ${packageJson.version} changelog (${String(section.length)} chars)`)
